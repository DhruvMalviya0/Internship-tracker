"""Apply login-gated applications through a browser session owned by the user.

This module deliberately does not log in, solve CAPTCHAs, or bypass site controls. It attaches to
an already authenticated Chromium session over CDP (or launches a user-supplied persistent profile),
fills fields whose values are known from the tracker profile, and only marks a job Applied after the
site visibly confirms submission.
"""
from __future__ import annotations

import json
import logging
import re
from dataclasses import dataclass, field
from datetime import date, timedelta
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

from . import db, verification
from .store import Conn

log = logging.getLogger(__name__)

_LOGIN_RE = re.compile(r"\b(?:log\s*in|login|sign\s*in|sign-in|create\s+an?\s+account)\b", re.I)
_SUCCESS_RE = re.compile(
    r"\b(?:thank\s+you|application\s+(?:has\s+been\s+)?submitted|application\s+received|successfully\s+applied|we(?:'|’)ve\s+received)\b",
    re.I,
)
_SUBMIT_RE = re.compile(r"\b(?:submit(?:\s+application)?|apply(?:\s+now)?|send\s+application|finish)\b", re.I)
_LOGIN_WARNING_RE = re.compile(r"login\s+required\s+to\s+apply", re.I)


@dataclass
class BrowserApplyResult:
    """Serializable result for one browser-applier attempt."""

    ok: bool
    status: str
    reason: str = ""
    message: str = ""
    url: str = ""
    filled: int = 0
    missing: list[str] = field(default_factory=list)
    job: dict | None = None

    def to_dict(self) -> dict:
        return {
            "ok": self.ok,
            "status": self.status,
            "reason": self.reason,
            "message": self.message,
            "url": self.url,
            "filled": self.filled,
            "missing": self.missing,
            "job": self.job,
        }


def _norm(value: Any) -> str:
    return re.sub(r"[^a-z0-9]+", " ", str(value or "").lower()).strip()


def parse_answer_draft(text: str) -> dict[str, str]:
    """Parse the ``label : answer`` draft format generated by ``bot.notes``."""
    out: dict[str, str] = {}
    for line in str(text or "").splitlines():
        if " : " not in line:
            continue
        label, value = line.split(" : ", 1)
        value = value.strip()
        if value and value != "[fill in]" and value != "[add link]":
            out[_norm(label)] = value
    return out


def _profile_values(profile: dict, job: dict, resume_path: str | None = None) -> dict[str, str]:
    contact = profile.get("contact") or {}
    location = profile.get("location") or {}
    name = str(profile.get("name") or "").strip()
    first, _, last = name.partition(" ")
    city = str(location.get("city") or "").strip()
    country = str(location.get("country") or "India").strip()
    loc = ", ".join(x for x in (city, country) if x)
    values = {
        "full_name": name,
        "first_name": first,
        "last_name": last,
        "preferred_name": str(profile.get("preferred_name") or "").strip(),
        "email": str(contact.get("email") or "").strip(),
        "phone": str(contact.get("phone") or "").strip(),
        "location": loc,
        "city": city,
        "country": country,
        "linkedin": str(contact.get("linkedin") or "").strip(),
        "github": str(contact.get("github") or "").strip(),
        "portfolio": str(contact.get("portfolio") or "").strip(),
        "cover_letter": str(job.get("note") or "").strip(),
        "resume": str(resume_path or "").strip(),
    }
    return {k: v for k, v in values.items() if v}


def _answer_for(label: str, answers: dict[str, str]) -> str:
    key = _norm(label)
    if not key:
        return ""
    if key in answers:
        return answers[key]
    for known, value in answers.items():
        if known in key or key in known:
            return value
    return ""


def value_for_field(meta: dict, profile: dict, job: dict, answers: dict[str, str], resume_path: str | None = None) -> str:
    """Return a conservative value for one extracted form control, or ``""`` to leave it alone."""
    label = _norm(" ".join(str(meta.get(k) or "") for k in ("label", "name", "placeholder", "aria_label")))
    values = _profile_values(profile, job, resume_path)

    answer = _answer_for(label, answers)
    if answer:
        return answer
    if "resume" in label or re.search(r"\bcv\b", label):
        return values.get("resume", "")
    if "cover letter" in label or "motivation letter" in label:
        return values.get("cover_letter", "")
    if re.search(r"\b(first|given) name\b", label):
        return values.get("first_name", "")
    if re.search(r"\b(last|family|sur) name\b", label):
        return values.get("last_name", "")
    if "preferred name" in label or "nickname" in label:
        return values.get("preferred_name", "") or values.get("first_name", "")
    if "email" in label:
        return values.get("email", "")
    if re.search(r"\b(phone|mobile|telephone|whatsapp)\b", label):
        return values.get("phone", "")
    if "linkedin" in label:
        return values.get("linkedin", "")
    if "github" in label:
        return values.get("github", "")
    if "portfolio" in label or "personal website" in label:
        return values.get("portfolio", "")
    if re.search(r"\b(full name|candidate name|your name|name)\b", label) and "company" not in label:
        return values.get("full_name", "")
    if re.search(r"\b(city|location|address)\b", label):
        return values.get("location", "")
    return ""


def build_fill_plan(fields: list[dict], profile: dict, job: dict, resume_path: str | None = None) -> list[dict]:
    """Build a testable fill plan from browser field metadata."""
    answers = parse_answer_draft(job.get("answers") or "")
    plan = []
    for field_meta in fields:
        value = value_for_field(field_meta, profile, job, answers, resume_path)
        if value:
            plan.append({"index": field_meta.get("index"), "value": value, "meta": field_meta})
    return plan


def is_login_page(url: str, text: str, password_fields: int = 0) -> bool:
    """Detect a login page without treating every page mentioning login as one."""
    url_hit = bool(re.search(r"/(?:login|signin|sign-in|auth)(?:[/?#]|$)", (url or "").lower()))
    text_hit = bool(_LOGIN_RE.search(text or ""))
    return url_hit or (password_fields > 0 and text_hit)


def is_login_required_job(job: dict) -> bool:
    """Whether a tracker row was explicitly held because the applier needed a login."""
    warnings = " ".join(job.get("warnings") or [])
    source = _norm(job.get("source"))
    platform = _norm(job.get("platform"))
    return bool(_LOGIN_WARNING_RE.search(warnings) or source in verification.LOGIN_REQUIRED_PLATFORMS
                or platform in {_norm(x) for x in verification.LOGIN_REQUIRED_PLATFORMS})


def _browser_imports():
    """Import Playwright lazily so scraping and unit tests work without the optional dependency."""
    try:
        from playwright.sync_api import sync_playwright
    except ImportError as exc:  # pragma: no cover - exercised by the CLI smoke path
        raise RuntimeError("Browser apply needs Playwright. Install requirements.txt, then run `python -m playwright install chromium`.") from exc
    return sync_playwright


class BrowserSession:
    """Attach to an existing Chromium session or launch a persistent user profile."""

    def __init__(self, cdp_url: str = "", user_data_dir: str = "", channel: str = "chrome"):
        self.cdp_url = cdp_url.strip()
        self.user_data_dir = user_data_dir.strip()
        self.channel = channel.strip() or "chrome"
        self._playwright = None
        self.browser = None
        self.context = None
        self._owned_context = False

    def __enter__(self):
        sync_playwright = _browser_imports()
        self._playwright = sync_playwright().start()
        if self.cdp_url:
            try:
                self.browser = self._playwright.chromium.connect_over_cdp(self.cdp_url)
            except Exception as exc:
                raise RuntimeError(
                    f"Could not attach to Chromium at {self.cdp_url}. Start the logged-in browser with remote debugging, "
                    "or pass --user-data-dir."
                ) from exc
            contexts = self.browser.contexts
            if not contexts:
                raise RuntimeError("The connected browser has no usable context.")
            self.context = contexts[0]
        else:
            if not self.user_data_dir:
                raise RuntimeError("Pass --cdp-url for an already-running browser or --user-data-dir for a persistent profile.")
            self.context = self._playwright.chromium.launch_persistent_context(
                self.user_data_dir, headless=False, channel=self.channel,
            )
            self._owned_context = True
        return self

    def new_page(self):
        if self.context is None:
            raise RuntimeError("Browser session is not open")
        return self.context.new_page()

    def __exit__(self, exc_type, exc, tb):
        try:
            if self._owned_context and self.context is not None:
                self.context.close()
            elif self.browser is not None:
                self.browser.close()
        finally:
            if self._playwright is not None:
                self._playwright.stop()


class BrowserApplier:
    """Fill and optionally submit one application in a user-controlled browser page."""

    def __init__(self, timeout_ms: int = 30_000):
        self.timeout_ms = timeout_ms

    @staticmethod
    def _body_text(page) -> str:
        try:
            return page.locator("body").inner_text(timeout=3_000)
        except Exception:
            return ""

    @staticmethod
    def _fields(page) -> list[dict]:
        controls = page.locator("input, textarea, select")
        fields = []
        for index in range(controls.count()):
            control = controls.nth(index)
            try:
                meta = control.evaluate(
                    """el => {
                      const labels = Array.from(document.labels || []);
                      const linked = labels.find(x => x.htmlFor && x.htmlFor === el.id);
                      const parent = el.closest('label');
                      const optionText = el.tagName.toLowerCase() === 'select'
                        ? Array.from(el.options).map(o => ({label: o.textContent.trim(), value: o.value})) : [];
                      return {
                        index: %d,
                        tag: el.tagName.toLowerCase(),
                        type: (el.getAttribute('type') || '').toLowerCase(),
                        name: el.getAttribute('name') || '',
                        id: el.id || '',
                        placeholder: el.getAttribute('placeholder') || '',
                        aria_label: el.getAttribute('aria-label') || '',
                        label: linked?.textContent?.trim() || parent?.textContent?.trim() || '',
                        required: !!el.required || el.getAttribute('aria-required') === 'true',
                        disabled: !!el.disabled || !!el.readOnly,
                        options: optionText,
                      };
                    }""" % index
                )
                fields.append(meta)
            except Exception:
                continue
        return fields

    @staticmethod
    def _visible(control) -> bool:
        try:
            return control.is_visible() and control.is_enabled()
        except Exception:
            return False

    def _fill(self, page, plan: list[dict]) -> tuple[int, list[str]]:
        filled = 0
        failures: list[str] = []
        controls = page.locator("input, textarea, select")
        for item in plan:
            index = item.get("index")
            meta = item.get("meta") or {}
            if index is None:
                continue
            control = controls.nth(index)
            if not self._visible(control):
                continue
            value = item["value"]
            try:
                if meta.get("type") == "file":
                    if Path(value).is_file():
                        control.set_input_files(value)
                        filled += 1
                    else:
                        failures.append(meta.get("label") or meta.get("name") or "resume")
                elif meta.get("tag") == "select":
                    options = meta.get("options") or []
                    desired = _norm(value)
                    option = next((o for o in options if _norm(o.get("label")) == desired), None)
                    option = option or next((o for o in options if desired and desired in _norm(o.get("label"))), None)
                    if option:
                        control.select_option(option["value"])
                        filled += 1
                elif meta.get("type") in ("checkbox", "radio", "hidden", "submit", "button", "reset"):
                    continue
                else:
                    control.fill(value)
                    filled += 1
            except Exception as exc:
                failures.append(meta.get("label") or meta.get("name") or f"field {index}")
                log.debug("Could not fill browser field %s: %s", meta, exc)
        return filled, failures

    def _required_missing(self, page, fields: list[dict]) -> list[str]:
        controls = page.locator("input, textarea, select")
        missing = []
        for field_meta in fields:
            if not field_meta.get("required") or field_meta.get("disabled"):
                continue
            if field_meta.get("type") in ("hidden", "submit", "button", "reset"):
                continue
            try:
                control = controls.nth(field_meta["index"])
                if not self._visible(control):
                    continue
                if field_meta.get("type") in ("checkbox", "radio"):
                    empty = not control.is_checked()
                else:
                    empty = not (control.input_value() or "").strip()
                if empty:
                    missing.append(field_meta.get("label") or field_meta.get("name") or f"field {field_meta['index']}")
            except Exception:
                continue
        return missing

    def _submit_control(self, page):
        buttons = page.locator("button, input[type='submit'], input[type='button'], a[href]")
        for index in range(buttons.count()):
            button = buttons.nth(index)
            if not self._visible(button):
                continue
            try:
                text = (button.inner_text() or button.get_attribute("value") or button.get_attribute("aria-label") or "").strip()
            except Exception:
                continue
            if _SUBMIT_RE.search(text) and not re.search(r"\b(?:filter|filters|search|preferences)\b", text, re.I):
                return button, text
        return None, ""

    def apply(self, page, job: dict, profile: dict, submit: bool = False, resume_path: str | None = None) -> BrowserApplyResult:
        url = str(job.get("apply_url") or job.get("url") or "")
        if not url:
            return BrowserApplyResult(False, "error", "missing_url", "This job has no application URL.")
        try:
            page.goto(url, wait_until="domcontentloaded", timeout=self.timeout_ms)
            try:
                page.wait_for_load_state("networkidle", timeout=5_000)
            except Exception:
                pass
        except Exception as exc:
            return BrowserApplyResult(False, "error", "navigation_failed", f"Could not open the application page: {exc}", url=url)

        for _step in range(3):
            current_url = getattr(page, "url", url)
            body = self._body_text(page)
            password_fields = page.locator("input[type='password']").count()
            if is_login_page(current_url, body, password_fields):
                return BrowserApplyResult(
                    False, "blocked", "browser_login_required",
                    "The attached browser is not logged in to this site. Sign in in that browser, then rerun the CLI.",
                    url=current_url,
                )

            try:
                html = page.content()
            except Exception:
                html = ""
            google = verification.check_google_docs(html)
            if google.detected:
                return BrowserApplyResult(False, "blocked", "external_form_required",
                                          f"The application still requires a separate form: {google.reason}", url=current_url)
            challenge = verification.check_human_verification(html_content=html, url=current_url)
            if challenge.detected:
                return BrowserApplyResult(False, "blocked", "human_verification_required",
                                          f"The application shows a human-verification challenge: {challenge.reason}", url=current_url)

            fields = self._fields(page)
            plan = build_fill_plan(fields, profile, job, resume_path)
            filled, failures = self._fill(page, plan)
            missing = self._required_missing(page, fields)
            if failures:
                missing = list(dict.fromkeys(missing + failures))
            if missing:
                return BrowserApplyResult(
                    False, "blocked", "required_fields", "Required fields still need attention: " + ", ".join(missing),
                    url=current_url, filled=filled, missing=missing,
                )
            if not submit:
                return BrowserApplyResult(True, "preview", "not_submitted",
                                          f"Filled {filled} known field(s); no application was submitted.",
                                          url=current_url, filled=filled)

            button, button_text = self._submit_control(page)
            if button is None:
                return BrowserApplyResult(False, "blocked", "submit_button_not_found",
                                          "No visible Apply/Submit button was found after filling the form.",
                                          url=current_url, filled=filled)
            try:
                button.click(timeout=self.timeout_ms)
                try:
                    page.wait_for_load_state("domcontentloaded", timeout=10_000)
                except Exception:
                    pass
                body_after = self._body_text(page)
                if _SUCCESS_RE.search(body_after):
                    return BrowserApplyResult(True, "submitted", "application_confirmed",
                                              f"The site confirmed submission after clicking “{button_text}”.",
                                              url=getattr(page, "url", current_url), filled=filled)
                if is_login_page(getattr(page, "url", current_url), body_after,
                                 page.locator("input[type='password']").count()):
                    return BrowserApplyResult(False, "blocked", "browser_login_required",
                                              "The site sent the browser to a login page while submitting.",
                                              url=getattr(page, "url", current_url), filled=filled)
            except Exception as exc:
                return BrowserApplyResult(False, "error", "submit_failed", f"Could not click the application button: {exc}",
                                          url=current_url, filled=filled)

            if _step < 2:
                continue
            return BrowserApplyResult(False, "blocked", "submission_not_confirmed",
                                      "The application button was clicked, but the site did not show a confirmation. The job was not marked Applied.",
                                      url=getattr(page, "url", current_url), filled=filled)

        return BrowserApplyResult(False, "blocked", "submission_not_confirmed", "The site did not confirm submission.", url=url)


def login_required_jobs(conn: Conn, user_id: int, limit: int = 25) -> list[dict]:
    """Return pending jobs held by the HTTP applier because a site login was needed."""
    rows = conn.execute(
        "SELECT id FROM jobs WHERE user_id=? AND status='User Review Pending' "
        "AND (warnings LIKE '%Login required to apply%' "
        "OR warnings LIKE '%Human verification required (login)%' "
        "OR warnings LIKE '%candidate account login%') ORDER BY id LIMIT ?",
        (user_id, limit),
    ).fetchall()
    return [job for r in rows if (job := db.get_job(conn, user_id, r["id"])) is not None]


def _set_browser_warning(conn: Conn, user_id: int, job_id: int, message: str) -> dict:
    job = db.get_job(conn, user_id, job_id)
    if not job:
        raise KeyError(job_id)
    warnings = job.get("warnings") or []
    if message not in warnings:
        warnings.append(message)
        conn.execute("UPDATE jobs SET warnings=? WHERE id=? AND user_id=?", (json.dumps(warnings), job_id, user_id))
        conn.commit()
    updated = db.get_job(conn, user_id, job_id)
    if updated is None:
        raise KeyError(job_id)
    return updated


def _mark_applied(conn: Conn, user_id: int, job_id: int, profile: dict) -> dict:
    followup_days = int(profile.get("drafts", {}).get("followup_days", 7))
    today = date.today().isoformat()
    current = db.get_job(conn, user_id, job_id)
    if current is None:
        raise KeyError(job_id)
    previous_notes = (current.get("user_notes") or "").strip()
    browser_note = "Applied automatically through the logged-in browser session."
    user_notes = f"{previous_notes}\n{browser_note}".strip() if previous_notes else browser_note
    return db.update_job_user_fields(
        conn, user_id, job_id,
        {
            "status": "Applied",
            "applied_date": today,
            "followup_date": (date.today() + timedelta(days=followup_days)).isoformat(),
            "user_notes": user_notes,
        },
        followup_days=followup_days,
    )


def run_browser_apply(
    conn: Conn,
    user_id: int,
    profile: dict,
    jobs: list[dict],
    session: BrowserSession,
    submit: bool = False,
    resume_path: str | None = None,
    timeout_ms: int = 30_000,
) -> list[dict]:
    """Apply a selected set of jobs and update the tracker only on visible confirmation."""
    runner = BrowserApplier(timeout_ms=timeout_ms)
    results = []
    for job in jobs:
        page = session.new_page()
        try:
            result = runner.apply(page, job, profile, submit=submit, resume_path=resume_path)
        finally:
            try:
                page.close()
            except Exception:
                pass
        if result.status == "submitted":
            result.job = _mark_applied(conn, user_id, job["id"], profile)
        elif result.status in ("blocked", "error"):
            result.job = _set_browser_warning(conn, user_id, job["id"], f"Browser applier: {result.message}")
        payload = {"job_id": job["id"], "company": job.get("company", ""), "role": job.get("role", ""),
                   "result": result.to_dict()}
        results.append(payload)
    return results
