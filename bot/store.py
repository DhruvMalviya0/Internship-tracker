"""One connection type for both databases: SQLite locally, Postgres when DATABASE_URL is set (deployed).

Code writes SQLite-style SQL (`?` placeholders, `:name` for dict params); for Postgres it's translated to
psycopg's `%s` / `%(name)s`. Rows behave like dicts in both (row["col"], dict(row))."""
from __future__ import annotations

import os
import re
import sqlite3
from pathlib import Path

PK = {"sqlite": "INTEGER PRIMARY KEY", "pg": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"}


def database_url() -> str:
    return os.environ.get("DATABASE_URL", "").strip()


def _translate(sql: str, named: bool) -> str:
    """`?` -> `%s` and `:name` -> `%(name)s` outside quoted strings; literal `%` -> `%%`."""
    out, i, quote = [], 0, None
    while i < len(sql):
        ch = sql[i]
        if quote:
            out.append("%%" if ch == "%" else ch)
            if ch == quote:
                quote = None
        elif ch in ("'", '"'):
            quote = ch
            out.append(ch)
        elif ch == "%":
            out.append("%%")
        elif ch == "?" and not named:
            out.append("%s")
        elif ch == ":" and named and i + 1 < len(sql) and (sql[i + 1].isalpha() or sql[i + 1] == "_") \
                and (i == 0 or sql[i - 1] != ":"):
            m = re.match(r":([A-Za-z_]\w*)", sql[i:])
            out.append(f"%({m.group(1)})s")
            i += len(m.group(0))
            continue
        else:
            out.append(ch)
        i += 1
    return "".join(out)


class Conn:
    """Thin wrapper so the rest of the code doesn't care which database it talks to."""

    def __init__(self, raw, dialect: str):
        self.raw = raw
        self.dialect = dialect

    @property
    def is_pg(self) -> bool:
        return self.dialect == "pg"

    def execute(self, sql: str, params=()):
        if self.is_pg:
            named = isinstance(params, dict)
            cur = self.raw.cursor()
            cur.execute(_translate(sql, named), params if named else tuple(params))
            return cur
        return self.raw.execute(sql, params)

    def executescript(self, script: str) -> None:
        if self.is_pg:
            for stmt in (s.strip() for s in script.split(";")):
                if stmt:
                    self.raw.execute(stmt)
            self.raw.commit()
        else:
            self.raw.executescript(script)

    def lock_runs(self) -> None:
        """Starts a transaction that serializes run starts across processes."""
        if self.is_pg:
            self.raw.execute("SELECT pg_advisory_xact_lock(424242)")
        else:
            self.raw.execute("BEGIN IMMEDIATE")

    def commit(self) -> None:
        self.raw.commit()

    def rollback(self) -> None:
        self.raw.rollback()

    def close(self) -> None:
        self.raw.close()

    def backup_to(self, path: Path) -> None:
        """SQLite only: copy the whole database to another file (used by --dry-run)."""
        dst = sqlite3.connect(path)
        self.raw.backup(dst)
        dst.close()


def connect_raw(target: str | Path | None) -> Conn:
    url = str(target) if target and str(target).startswith(("postgres://", "postgresql://")) else ""
    if url:
        import psycopg
        from psycopg.rows import dict_row
        # prepare_threshold=None: works through PgBouncer / Neon's pooled connection strings too.
        raw = psycopg.connect(url, row_factory=dict_row, autocommit=False, connect_timeout=15, prepare_threshold=None)
        return Conn(raw, "pg")
    path = Path(target)
    path.parent.mkdir(parents=True, exist_ok=True)
    raw = sqlite3.connect(path, timeout=15)
    raw.row_factory = sqlite3.Row
    raw.execute("PRAGMA journal_mode=WAL")
    raw.execute("PRAGMA synchronous=NORMAL")
    raw.execute("PRAGMA foreign_keys=ON")
    return Conn(raw, "sqlite")
